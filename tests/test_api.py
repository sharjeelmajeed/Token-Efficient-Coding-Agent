from token_agent.api import create_app

from .conftest import live_client, session, start, wait_status


def test_complete_approval_flow_and_behavior(connected):
    client, app, env = connected
    sid = session(client, env)
    run = start(client, sid)
    waiting = wait_status(client, sid, {"waiting_approval"})
    approval = waiting["pending_approvals"][0]
    assert "-    return a - b" in approval["diff"]
    assert (env["repo"] / "calculator.py").read_text().endswith("return a - b\n")
    response = client.post(
        f"/sessions/{sid}/approvals/{approval['id']}", json={"decision": "approve_once"}
    )
    assert response.status_code == 200
    completed = wait_status(client, sid, {"completed"})
    assert completed["run"]["outcome"] == "completed_unverified"
    # Controlled fixture only: verify the actual changed behavior independently of the agent.
    namespace = {}
    exec(compile((env["repo"] / "calculator.py").read_text(), "fixture", "exec"), namespace)
    assert namespace["add"](2, 3) == 5
    assert namespace["add"](-2, -3) == -5
    assert namespace["add"](0, 7) == 7
    metrics = client.get(f"/metrics/runs/{run}").json()
    assert metrics["benchmark_evidence"] is False
    assert metrics["usage"]
    assert all(u["amount"] == 0 for u in metrics["usage"])
    assert app.state.store.approval(approval["id"])["status"] == "consumed"


@pytest.mark.parametrize("decision", ["deny", "deny_with_feedback"])
def test_denial_never_writes(connected, decision):
    client, app, env = connected
    sid = session(client, env)
    start(client, sid)
    waiting = wait_status(client, sid, {"waiting_approval"})
    aid = waiting["pending_approvals"][0]["id"]
    assert (
        client.post(
            f"/sessions/{sid}/approvals/{aid}",
            json={"decision": decision, "feedback": "Do not edit this file"},
        ).status_code
        == 200
    )
    wait_status(client, sid, {"completed"})
    assert "return a - b" in (env["repo"] / "calculator.py").read_text()
    decisions = [e for e in app.state.store.events(sid) if e["type"] == "approval_decision"]
    assert decisions[0]["payload"]["user"] == "first"


def test_stale_patch_rejected_after_approval(connected):
    client, _, env = connected
    sid = session(client, env)
    start(client, sid)
    data = wait_status(client, sid, {"waiting_approval"})
    aid = data["pending_approvals"][0]["id"]
    changed = "def add(a, b):\n    return 123\n"
    (env["repo"] / "calculator.py").write_text(changed)
    client.post(f"/sessions/{sid}/approvals/{aid}", json={"decision": "approve_once"})
    paused = wait_status(client, sid, {"paused"})
    assert "File changed" in paused["run"]["outcome"]
    assert (env["repo"] / "calculator.py").read_text() == changed


